CREATE TABLE jobs (
  id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  company_id      BIGINT UNSIGNED NOT NULL,
  category_id     BIGINT UNSIGNED NOT NULL,
  title           VARCHAR(120) NOT NULL,
  slug            VARCHAR(140) NOT NULL UNIQUE,
  type            ENUM('full_time','part_time','internship','contract') NOT NULL,
  level           ENUM('internship','entry','junior','mid') NOT NULL,
  work_mode       ENUM('onsite','hybrid','remote') NOT NULL,
  location        VARCHAR(100) NULL,
  salary_min      INT UNSIGNED NULL,
  salary_max      INT UNSIGNED NULL,
  show_salary     BOOLEAN NOT NULL DEFAULT TRUE,
  skills          JSON NOT NULL,
  description     TEXT NOT NULL,
  requirements    TEXT NOT NULL,
  deadline        DATE NOT NULL,
  status          ENUM('draft','open','closed') NOT NULL DEFAULT 'draft',
  moderation_note VARCHAR(500) NULL,
  views           INT UNSIGNED NOT NULL DEFAULT 0,
  created_at      DATETIME(3) NOT NULL,
  updated_at      DATETIME(3) NOT NULL,
  INDEX idx_jobs_public (status, deadline, created_at),
  INDEX idx_jobs_level (level),
  INDEX idx_jobs_mode (work_mode),
  FULLTEXT INDEX ft_jobs_text (title, description),
  CONSTRAINT fk_jobs_company  FOREIGN KEY (company_id)  REFERENCES companies(id) ON DELETE CASCADE,
  CONSTRAINT fk_jobs_category FOREIGN KEY (category_id) REFERENCES categories(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;